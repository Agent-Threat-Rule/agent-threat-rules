/**
 * Tests for the Gemara catalogs generated from the category registry
 * (scripts/generate-gemara-catalogs.ts) and for the workflow that publishes them
 * (.github/workflows/publish-gemara.yml).
 *
 * What is pinned:
 *
 * - The committed catalogs are exactly the generator output, and the bundle
 *   directory holds nothing else. Editing the registry or the editorial source
 *   without regenerating fails here, in CI, before merge.
 * - The vector catalog is the registry: same ids, same order, the registry's
 *   descriptions. A registry category with no editorial entry, an editorial
 *   entry for a category the registry lacks, a vector no threat reaches, a
 *   reference that does not resolve, or a bundle version that does not match
 *   the registry version stops the generator.
 * - The bundle assembles the way go-gemara's Assemble walks it: from the root,
 *   `imports` backed by file:// mapping-references reach every catalog, and no
 *   mapping-reference without a url is left unmatched.
 * - The publish workflow cannot publish on a push to main or on a pull request.
 *   It runs on release tags and manual dispatch from a tag; every action is
 *   pinned to a commit SHA; only the publish job can write packages or mint an
 *   OIDC token, and it runs no npm; signing is keyless on the source registry
 *   and nothing is promoted to a second one.
 * - The "already published?" step, run verbatim against a stand-in oras,
 *   publishes an absent version, skips a version published with identical
 *   catalogs, and refuses a version published with different catalogs or one
 *   it cannot read.
 */
import { afterEach, describe, expect, it } from "vitest";
import { createHash } from "node:crypto";
import { chmodSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import yaml from "js-yaml";
import {
  CATALOG_DIR,
  CatalogError,
  REGISTRY_REF_ID,
  generate,
  loadInputs,
  staleFiles,
  type Generated,
} from "../scripts/generate-gemara-catalogs.js";
import { HAS_JQ, cleanSandboxes, put, runBlock, runStep, sandbox, workflowDoc } from "./workflow-step-harness.js";

type Doc = Record<string, any>;

const REPO_ROOT = resolve(__dirname, "..");
const WORKFLOW = join(REPO_ROOT, ".github", "workflows", "publish-gemara.yml");
const GATE_STEP = "Check whether this version is already published";
const TAG_STEP = "Require a release tag";

const [registryRaw, editorialRaw] = loadInputs();
const generated: Generated = generate(registryRaw, editorialRaw);
const docs = new Map(generated.files.map((f) => [f.file, yaml.load(f.content) as Doc]));
const registry = registryRaw as Doc;
const editorial = editorialRaw as Doc;
const ofType = (type: string): Doc => [...docs.values()].find((d) => d.metadata.type === type) as Doc;
const generateWith = (reg: Doc, ed: Doc): Generated => generate(reg, ed);

afterEach(cleanSandboxes);

describe("committed Gemara catalogs", () => {
  it("are exactly the generator output, and nothing else sits in the bundle directory", () => {
    expect(staleFiles(generated)).toEqual([]);
  });

  it("say they are generated, and from what", () => {
    for (const { content } of generated.files) {
      expect(content.startsWith("# GENERATED by scripts/generate-gemara-catalogs.ts")).toBe(true);
    }
  });
});

describe("the vector catalog is a projection of the category registry", () => {
  const vectors = ofType("VectorCatalog").vectors as Doc[];

  it("has one vector per registry category, same ids, same order", () => {
    expect(vectors.map((v) => v.id)).toEqual(registry.categories.map((c: Doc) => c.id));
  });

  it("carries the registry's description of each category", () => {
    for (const [i, category] of (registry.categories as Doc[]).entries()) {
      const words = String(category.description).replace(/\s+/g, " ").trim().replace(/(\w)- (?=\w)/g, "$1-");
      expect(vectors[i].description).toBe(words);
    }
  });

  it("stamps the bundle version and the registry's draft status on every catalog", () => {
    const [major, minor] = generated.version.split(".");
    expect(`${major}.${minor}`).toBe(String(registry.version));
    for (const doc of docs.values()) {
      expect(doc.metadata.version).toBe(generated.version);
      expect(doc.metadata.draft === true).toBe(registry.status === "draft");
    }
  });

  it("projects no other registry field (no rule counts, no severities)", () => {
    for (const { content } of generated.files) {
      expect(content).not.toMatch(/rule_count|typical_severity|typical_scan_target/);
    }
  });
});

describe("the generator refuses inputs that disagree", () => {
  const expectRefusal = (reg: Doc, ed: Doc, message: RegExp): void => {
    let thrown: unknown;
    try {
      generateWith(reg, ed);
    } catch (error) {
      thrown = error;
    }
    expect(thrown).toBeInstanceOf(CatalogError);
    expect((thrown as Error).message).toMatch(message);
  };

  it("a registry category with no editorial entry", () => {
    const reg = structuredClone(registry);
    reg.categories.push({ id: "new-category", description: "A category added to the registry." });
    expectRefusal(reg, editorial, /registry category "new-category" has no entry/);
  });

  it("an editorial vector for a category the registry does not have", () => {
    const ed = structuredClone(editorial);
    ed["vector-catalog"].vectors["ghost-category"] = { title: "Ghost", group: "via-content" };
    expectRefusal(registry, ed, /"ghost-category" is not a category in the registry/);
  });

  it("a registry category that no threat reaches", () => {
    const ed = structuredClone(editorial);
    for (const threat of ed["threat-catalog"].threats as Doc[]) {
      for (const ref of threat.vectors as Doc[]) {
        ref.entries = ref.entries.filter((e: Doc) => e["reference-id"] !== "data-poisoning");
      }
    }
    expectRefusal(registry, ed, /registry category "data-poisoning" is not reached by any threat/);
  });

  it("a threat pointing at a vector that does not exist", () => {
    const ed = structuredClone(editorial);
    ed["threat-catalog"].threats[0].vectors[0].entries.push({ "reference-id": "prompt-injektion" });
    expectRefusal(registry, ed, /"prompt-injektion" is not an entry of ATR-AI-AGENT-VECTOR-CATALOG/);
  });

  it("a control citing a rule category the registry does not have", () => {
    const ed = structuredClone(editorial);
    const guideline = (ed["control-catalog"].controls[0].guidelines as Doc[]).find((g) => g["reference-id"] === REGISTRY_REF_ID) as Doc;
    guideline.entries.push({ "reference-id": "not-a-category" });
    expectRefusal(registry, ed, /"not-a-category" is not an entry of ATR/);
  });

  it("a bundle version whose MAJOR.MINOR is not the registry version", () => {
    const ed = structuredClone(editorial);
    ed.bundle.version = "1.1.0";
    expectRefusal(registry, ed, /MAJOR\.MINOR must equal the registry version 1\.0/);
  });
});

describe("the bundle assembles from its root", () => {
  // go-gemara bundle.Assemble: follow `imports` and `extends` whose
  // mapping-reference has a url; then every url-less mapping-reference must
  // match the metadata.id of an artifact in the set.
  function assemble(root: string): { files: string[]; unmatched: string[] } {
    const queue = [root];
    const files: string[] = [];
    while (queue.length > 0) {
      const file = queue.shift() as string;
      if (files.includes(file)) continue;
      files.push(file);
      const doc = docs.get(file) as Doc;
      const urls = new Map(((doc.metadata["mapping-references"] ?? []) as Doc[]).filter((r) => r.url).map((r) => [r["id"], String(r.url)]));
      for (const edge of [...(doc.imports ?? []), ...(doc.extends ?? [])] as Doc[]) {
        const url = urls.get(edge["reference-id"]);
        if (url === undefined) continue;
        expect(url).toMatch(/^file:\/\/\.\/[a-z0-9-]+\.yaml$/);
        queue.push(url.slice("file://./".length));
      }
    }
    const ids = new Set(files.map((f) => (docs.get(f) as Doc).metadata.id));
    const unmatched = files.flatMap((f) =>
      ((docs.get(f) as Doc).metadata["mapping-references"] ?? [])
        .filter((r: Doc) => !r.url && !ids.has(r.id))
        .map((r: Doc) => `${f}: ${r.id}`),
    );
    return { files, unmatched };
  }

  it("reaches every catalog from the root and leaves nothing unmatched", () => {
    const { files, unmatched } = assemble(generated.root);
    expect([...files].sort()).toEqual(generated.files.map((f) => f.file).sort());
    expect(unmatched).toEqual([]);
  });

  it("has a ControlCatalog root, which is how the publish action validates a catalog root", () => {
    expect((docs.get(generated.root) as Doc).metadata.type).toBe("ControlCatalog");
    expect(generated.files[0].file).toBe(generated.root);
  });

  it("references sibling catalogs by their metadata id and version", () => {
    for (const doc of docs.values()) {
      for (const ref of (doc.metadata["mapping-references"] ?? []) as Doc[]) {
        expect(ref.url).toMatch(/^[a-zA-Z][a-zA-Z0-9+.-]*:[^\s]+$/); // Gemara #MappingReference.url
        if (!String(ref.url).startsWith("file://")) continue;
        const target = docs.get(String(ref.url).slice("file://./".length)) as Doc;
        expect(ref.id).toBe(target.metadata.id);
        expect(ref.version).toBe(target.metadata.version);
      }
    }
  });
});

describe("publish-gemara.yml", () => {
  const wf = workflowDoc(WORKFLOW) as Doc;
  const triggers = (wf.on ?? wf[true as unknown as string]) as Doc;
  const jobs = wf.jobs as Doc;

  it("runs on release tags and manual dispatch only, never on a branch push or a pull request", () => {
    expect(Object.keys(triggers).sort()).toEqual(["push", "workflow_dispatch"]);
    expect(Object.keys(triggers.push)).toEqual(["tags"]);
    for (const pattern of triggers.push.tags as string[]) expect(pattern.startsWith("v")).toBe(true);
  });

  it("skips release-tag runs until GEMARA_PUBLISH_ON_TAGS is set, so the first publish is a manual run", () => {
    const cond = String(jobs.verify.if ?? "");
    expect(cond).toContain("github.event_name == 'workflow_dispatch'");
    expect(cond).toContain("vars.GEMARA_PUBLISH_ON_TAGS == 'true'");
    expect(jobs.publish.needs).toBe("verify");
  });

  it("pins every action to a commit SHA", () => {
    for (const job of Object.values(jobs) as Doc[]) {
      for (const step of job.steps as Doc[]) {
        if (step.uses === undefined) continue;
        expect(step.uses).toMatch(/^[\w.-]+\/[\w.-]+@[0-9a-f]{40}$/);
      }
    }
  });

  it("gives write permission and the OIDC token to the publish job only, which runs no npm", () => {
    expect(wf.permissions).toEqual({ contents: "read" });
    expect(jobs.verify.permissions).toEqual({ contents: "read" });
    expect(jobs.publish.permissions).toEqual({ contents: "read", packages: "write", "id-token": "write" });
    for (const step of jobs.publish.steps as Doc[]) expect(String(step.run ?? "")).not.toMatch(/\bnp[mx]\b/);
  });

  it("publishes the generated root from the generated directory, signed, to one registry", () => {
    expect(jobs.publish.env.CATALOG_DIR).toBe(relative(REPO_ROOT, CATALOG_DIR).split("\\").join("/"));
    expect(jobs.publish.env.ROOT_FILE).toBe(generated.root);
    const publish = (jobs.publish.steps as Doc[]).find((s) => String(s.uses ?? "").startsWith("gemaraproj/gemara-publish-action@")) as Doc;
    expect(publish.with).toMatchObject({
      registry: "ghcr.io",
      validate: "true",
      sign_source: "true",
      verify_source: "true",
      promote_to_destination: "false",
    });
    expect(publish.with.allowed_identity_regex).toContain("publish-gemara\\.yml@refs/tags/v");
  });

  it("validates against the Gemara release the catalogs declare", () => {
    const fetch = (jobs.verify.steps as Doc[]).find((s) => s.env?.GEMARA_TAG !== undefined) as Doc;
    expect(fetch.env.GEMARA_TAG).toBe(`v${editorial.bundle["gemara-version"]}`);
    expect(fetch.env.GEMARA_SHA).toMatch(/^[0-9a-f]{40}$/);
  });
});

describe("publish-gemara.yml: release tag guard", () => {
  const script = runBlock(WORKFLOW, "verify", TAG_STEP);
  const run = (ref: string) => runStep(sandbox("gemara-tag-", { "README.md": "fixture\n" }), script, { REF: ref });

  it.each(["refs/heads/main", "refs/tags/v3", "refs/tags/pyatr-v0.3.1", "refs/tags/v4.2.0-rc1"])("refuses %s", (ref) => {
    expect(run(ref).status).not.toBe(0);
  });

  it("accepts a release tag", () => {
    expect(run("refs/tags/v4.2.0").status).toBe(0);
  });
});

describe.skipIf(!HAS_JQ)("publish-gemara.yml: already-published gate", () => {
  const script = runBlock(WORKFLOW, "publish", GATE_STEP);
  const DIR = "spec/category-registry/gemara";
  const REF = "ghcr.io/fixture-owner/fixture-repo/gemara";

  const layer = (file: string, content: string) => ({
    mediaType: "application/vnd.gemara.artifact.v1+yaml",
    digest: `sha256:${createHash("sha256").update(content).digest("hex")}`,
    size: Buffer.byteLength(content),
    annotations: { "org.opencontainers.image.title": file },
  });

  /**
   * A stand-in oras. `manifest fetch <tag>` prints $FAKE_ORAS_MANIFEST or fails with
   * $FAKE_ORAS_ERROR; `resolve` prints a digest; `manifest fetch <...>.sig` succeeds
   * only when $FAKE_ORAS_SIGNED is set.
   */
  function gate(remote: { manifest?: object; error?: string; signed?: boolean }, extraEnv: Record<string, string> = {}) {
    const files = Object.fromEntries(generated.files.map((f) => [`${DIR}/${f.file}`, f.content]));
    const sb = sandbox("gemara-gate-", files);
    put(sb.work, `${DIR}/src/editorial.yaml`, readFileSync(join(CATALOG_DIR, "src", "editorial.yaml"), "utf8"));
    const manifestPath = join(sb.root, "manifest.json");
    writeFileSync(manifestPath, JSON.stringify(remote.manifest ?? {}));
    const oras = join(sb.root, "bin", "oras");
    writeFileSync(
      oras,
      "#!/usr/bin/env bash\n" +
        'if [ "$1" = resolve ]; then echo "sha256:$(printf %064d 0)"; exit 0; fi\n' +
        '[ "$1 $2" = "manifest fetch" ] || { echo "unexpected oras call: $*" >&2; exit 2; }\n' +
        'case "$3" in *.sig) [ -n "${FAKE_ORAS_SIGNED:-}" ] && { echo "{}"; exit 0; }; echo "Error: not found" >&2; exit 1 ;; esac\n' +
        'if [ -n "${FAKE_ORAS_ERROR:-}" ]; then echo "$FAKE_ORAS_ERROR" >&2; exit 1; fi\ncat "$FAKE_ORAS_MANIFEST"\n',
    );
    chmodSync(oras, 0o755);
    const result = runStep(sb, script, {
      CATALOG_DIR: DIR,
      VERSION: generated.version,
      REPO_REF: REF,
      FAKE_ORAS_MANIFEST: manifestPath,
      FAKE_ORAS_ERROR: remote.error ?? "",
      FAKE_ORAS_SIGNED: remote.signed === false ? "" : "1",
      FIRST_PUBLISH: "false",
      ...extraEnv,
    });
    return { result, output: readFileSync(sb.env.GITHUB_OUTPUT, "utf8") };
  }

  const published = (tweak: (layers: object[]) => object[] = (l) => l) => ({
    manifest: { schemaVersion: 2, layers: tweak(generated.files.map((f) => layer(f.file, f.content))) },
  });

  it("publishes a version that is not in the registry yet", () => {
    const { result, output } = gate({ error: `Error: ${REF}:${generated.version}: manifest unknown` });
    expect(result.status).toBe(0);
    expect(output).toContain("publish=true");
  });

  it("publishes when oras reports the tag as not found, as GHCR did on the first publish", () => {
    const ref = `${REF}:${generated.version}`;
    const { result, output } = gate({
      error: `Error response from registry: failed to fetch the content of "${ref}": ${ref}: not found`,
    });
    expect(result.status).toBe(0);
    expect(output).toContain("publish=true");
  });

  it("does not read any other 'not found' as unpublished", () => {
    const { result, output } = gate({ error: "Error: credentials helper not found" });
    expect(result.status).not.toBe(0);
    expect(output).not.toContain("publish=");
  });

  it("pushes nothing when the version is published with these exact catalogs", () => {
    const { result, output } = gate(published());
    expect(result.status).toBe(0);
    expect(output).toContain("publish=false");
  });

  it("refuses to overwrite a version published with different catalogs", () => {
    const { result, output } = gate(published((layers) => [...layers.slice(1), layer(generated.files[0].file, "changed")]));
    expect(result.status).not.toBe(0);
    expect(output).not.toContain("publish=");
    expect(result.stdout).toContain("Bump bundle.version");
  });

  it("refuses when the version is published with a catalog missing", () => {
    const { result, output } = gate(published((layers) => layers.slice(1)));
    expect(result.status).not.toBe(0);
    expect(output).not.toContain("publish=");
  });

  it("refuses when the version is published with identical catalogs but no signature", () => {
    const { result, output } = gate({ ...published(), signed: false });
    expect(result.status).not.toBe(0);
    expect(output).not.toContain("publish=");
  });

  it.each(["denied: requested access to the resource is denied", "unauthorized: authentication required"])(
    "treats %s as unknown, not as absent, unless first_publish is set",
    (error) => {
      const refused = gate({ error });
      expect(refused.result.status).not.toBe(0);
      expect(refused.output).not.toContain("publish=");
      const first = gate({ error }, { FIRST_PUBLISH: "true" });
      expect(first.result.status).toBe(0);
      expect(first.output).toContain("publish=true");
    },
  );

  it("refuses to publish when it cannot tell whether the version exists", () => {
    const { result, output } = gate({ error: "Error: Get https://ghcr.io/v2/: dial tcp: i/o timeout" });
    expect(result.status).not.toBe(0);
    expect(output).not.toContain("publish=");
  });
});
